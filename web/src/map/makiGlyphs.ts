/**
 * Rasterises one SVG into a coverage mask using an offscreen canvas.
 *
 * Args:
 *   svg: SVG markup.
 *   size: Output edge length in device pixels.
 *
 * Returns:
 *   The glyph's alpha channel.
 *
 * Raises:
 *   Error: If the SVG cannot be decoded or a 2D context is unavailable.
 */
async function rasterize(svg: string, size: number): Promise<GlyphMask> {
  const url = URL.createObjectURL(new Blob([svg], { type: 'image/svg+xml' }));
  try {
    const img = new Image(size, size);
    img.src = url;
    await img.decode();
    const canvas = document.createElement('canvas');
    canvas.width = size;
    canvas.height = size;
    const ctx = canvas.getContext('2d');
    if (!ctx) throw new Error('2D canvas context unavailable');
    // SVG 是向量，直接畫到目標尺寸不會模糊
    ctx.drawImage(img, 0, 0, size, size);
    const rgba = ctx.getImageData(0, 0, size, size).data;
    const alpha = new Uint8Array(size * size);
    for (let i = 0; i < alpha.length; i++) alpha[i] = rgba[i * 4 + 3] ?? 0;
    return { size, alpha };
  } finally {
    URL.revokeObjectURL(url);
  }
}

// 快取 Promise（而非結果）：同一圖示被多個圖磚同時要求時只解碼一次
const glyphs = new Map<MakiName, Promise<GlyphMask | undefined>>();

/**
 * Rasterises a Maki glyph on first use and caches it.
 *
 * Args:
 *   maki: Maki glyph name.
 *
 * Returns:
 *   The mask, or undefined if the SVG failed to decode (callers fall back to a plain dot).
 */
export function loadMakiGlyph(maki: MakiName): Promise<GlyphMask | undefined> {
  let pending = glyphs.get(maki);
  if (!pending) {
    const size = glyphPixelSize(MAKI_ICON_DIAMETER, iconPixelRatio());
    pending = rasterize(MAKI_SVGS[maki], size).catch((error: unknown) => {
      console.warn(`Maki 圖示 ${maki} 載入失敗，改以圓點顯示`, error);
      return undefined;
    });
    glyphs.set(maki, pending);
  }
  return pending;
}